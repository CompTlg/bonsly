#!/usr/bin/env python3
"""
Reference data for the spectral unit tests, taken from Mitsuba 3 (variant scalar_spectral).

  python3 oracle.py golden   writes ../golden_data.hpp   (used by unittests/spectral/upsampling.cpp)
  python3 oracle.py tables   writes cie_tables.hpp       (OPTIONAL: CIE 1931 2-degree CMFs and D65 at 1 nm,
                                                          360..830 nm, in case you do not want to type in
                                                          the tables from cvrl.org yourself)

Mitsuba is BSD-licensed. Its CMFs are the official CIE 1931 table (checked at 450/500/555/600 nm against the
published values, 4 digits), linearly interpolated between 1 nm samples and zero outside [360, 830] nm.
Its RGB upsampling (srgb_model_*) is the Jakob & Hanika 2019 model.
"""
import os
import sys

import numpy as np
import mitsuba as mi

mi.set_variant("scalar_spectral")

HERE = os.path.dirname(os.path.abspath(__file__))

# every 10 nm, plus half-integer wavelengths to exercise the interpolation of the CMF table
LAMBDAS = [float(l) for l in range(360, 831, 10)] + [365.5 + 30.0 * k for k in range(16)]
ALBEDO_LAMBDAS = [float(l) for l in range(360, 831, 10)]
NUM_COLORS = 60
SEED = 2024


def cmf(l):
    return np.array(mi.cie1931_xyz(float(l)), dtype=np.float64)


def d65(l):
    return float(mi.cie_d65(float(l)))


def albedo(rgb, l):
    coeffs = mi.srgb_model_fetch(mi.ScalarColor3f(*[float(c) for c in rgb]))
    return float(np.array(mi.srgb_model_eval(coeffs, mi.Spectrum(float(l))))[0])


def fmt_float(v):
    s = f"{float(v):.8g}"
    if not any(ch in s for ch in ".eEn"):  # "360" is not a float literal in C++, "360.0f" is
        s += ".0"
    return s + "f"


def fmt_row(values):
    return "{" + ", ".join(fmt_float(v) for v in values) + "}"


def write_golden():
    rng = np.random.default_rng(SEED)
    colors = rng.random((NUM_COLORS, 3))
    d65_560 = d65(560.0)

    out = []
    out.append("// Generated by unittests/spectral/tools/oracle.py from Mitsuba 3 (scalar_spectral). Do not edit.\n")
    out.append("#pragma once\n\nnamespace golden\n{\n")
    out.append(f"    inline constexpr int NumLambdas = {len(LAMBDAS)};\n")
    out.append("    inline constexpr float Lambdas[NumLambdas] = " + fmt_row(LAMBDAS) + ";\n")
    out.append("    // CIE 1931 2-degree colour matching functions (x, y, z) at Lambdas\n")
    out.append("    inline constexpr float Cmf[NumLambdas][3] = {\n")
    out.append(",\n".join("        " + fmt_row(cmf(l)) for l in LAMBDAS) + "\n    };\n")
    out.append("    // D65 relative to its value at 560 nm (the absolute scale of your table does not matter)\n")
    out.append("    inline constexpr float D65Ratio[NumLambdas] = " + fmt_row([d65(l) / d65_560 for l in LAMBDAS]) + ";\n")
    out.append(f"    inline constexpr int NumColors = {NUM_COLORS};\n")
    out.append(f"    inline constexpr int NumAlbedoLambdas = {len(ALBEDO_LAMBDAS)};\n")
    out.append("    inline constexpr float AlbedoLambdas[NumAlbedoLambdas] = " + fmt_row(ALBEDO_LAMBDAS) + ";\n")
    out.append("    // random sRGB colours in [0,1]^3 and Mitsuba's reflectance spectrum for each, sampled at AlbedoLambdas\n")
    out.append("    inline constexpr float Colors[NumColors][3] = {\n")
    out.append(",\n".join("        " + fmt_row(c) for c in colors) + "\n    };\n")
    out.append("    inline constexpr float Albedo[NumColors][NumAlbedoLambdas] = {\n")
    out.append(",\n".join("        " + fmt_row([albedo(c, l) for l in ALBEDO_LAMBDAS]) for c in colors) + "\n    };\n")
    out.append("}\n")
    path = os.path.join(HERE, "..", "golden_data.hpp")
    with open(path, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(path))


def write_tables():
    ls = range(360, 831)
    lines = ["// CIE 1931 2-degree colour matching functions (x, y, z) and CIE D65 relative power, 360..830 nm, 1 nm steps.\n",
             "// Source: Mitsuba 3 (BSD-licensed), which uses the official CIE tables.\n",
             "static constexpr float CieXyz[471][3] = {\n"]
    lines.append(",\n".join("    " + fmt_row(cmf(l)) for l in ls) + "\n};\n")
    lines.append("static constexpr float D65[471] = {\n    " + ",\n    ".join(fmt_float(d65(l)) for l in ls) + "\n};\n")
    with open(os.path.join(HERE, "cie_tables.hpp"), "w") as f:
        f.write("".join(lines))
    print("wrote", os.path.join(HERE, "cie_tables.hpp"))


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("golden", "tables"):
        print(__doc__)
        sys.exit(1)
    write_golden() if sys.argv[1] == "golden" else write_tables()
